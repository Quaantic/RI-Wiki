// Bundle the imported information with the JavaScript deployment too. This is
// deliberately limited to the requested pages and never includes Update Log.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const wiki = JSON.parse(fs.readFileSync(path.join(root,'content/wiki-data.json')));
const game = JSON.parse(fs.readFileSync(path.join(root,'content/game-data.json')));
const find = (nodes,id) => { for (const node of nodes || []) { if (node.id===id) return node; const match=find(node.children,id); if(match)return match; } };
const routes=['life/frost-generators','life/golden-points','life/golden-research-milestones','main/californium-milestones','main/astatine-power','life/frost-conversion','money-island/energies'];
const pages=routes.map(route=>{
  const [cat,id]=route.split('/');
  const page=find(wiki.categories.find(c=>c.id===cat)?.subcategories,id);
  if(!page?.sections?.length)throw new Error(`Missing imported content: ${route}`);
  return {route,page};
});
const calculators=Object.fromEntries(routes.filter(route=>game.calculators.pages[route]).map(route=>[route,game.calculators.pages[route]]));
const stages=Object.fromEntries(routes.filter(route=>game.progression.stages[route]).map(route=>[route,game.progression.stages[route]]));
const upgrades=Object.fromEntries(['life/frost-upgrades','life/golden-research-upgrades','main/astatine-upgrades'].map(route=>[route,game.upgrades.sections[game.upgrades.routes[route]]]));
const patch={id:'game-notes-2026-11-v1',pages,calculators,stages,upgrades,redirects:wiki.redirects};
fs.writeFileSync(path.join(root,'js/data/imported-notes.js'),'// Generated by scripts/build-content-patch.cjs from the five supplied notes.\nexport const IMPORTED_NOTES = '+JSON.stringify(patch,null,2)+';\n');
console.log('Bundled imported content for '+routes.length+' exact routes.');
